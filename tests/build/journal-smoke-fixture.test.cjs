const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { createJournalFixture } = require('../../scripts/build/journal-smoke-fixture.cjs')

test('journal smoke uses only committed synthetic records in a fresh test directory', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'g2a-fixture-test-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const sourceDir = path.resolve(__dirname, '../testdata/g2a')
  const directory = await createJournalFixture({ sourceDir, outputParent: root })
  assert.deepEqual((await fs.readdir(directory)).sort(), ['Cargo.json', 'Journal.20260101.01.log', 'Materials.json', 'NavRoute.json', 'Status.json'])
  const records = await fs.readFile(path.join(directory, 'Journal.20260101.01.log'), 'utf8')
  assert.match(records, /SYNTHETIC-A/)
  assert.match(records, /Fixture Beta/)
  assert.notEqual(directory, await createJournalFixture({ sourceDir, outputParent: root }))
  assert.equal(await fs.readFile(path.join(sourceDir, 'replay.jsonl'), 'utf8'), records)
})
