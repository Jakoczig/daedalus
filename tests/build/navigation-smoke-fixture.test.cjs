const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const os = require('node:os')
const path = require('node:path')
const { createNavigationFixture } = require('../../scripts/build/navigation-smoke-fixture.cjs')

test('navigation fixture copies only fabricated journal and route, never adjacent private data', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'g2b-fixture-test-'))
  t.after(() => fs.rm(root, { recursive: true, force: true }))
  const sourceDir = path.resolve(__dirname, '../testdata/g2b')
  const directory = await createNavigationFixture({ sourceDir, outputParent: root })
  assert.deepEqual((await fs.readdir(directory)).sort(), ['Journal.20260101.01.log', 'NavRoute.json'])
  const journal = await fs.readFile(path.join(directory, 'Journal.20260101.01.log'), 'utf8')
  assert.match(journal, /SYNTHETIC-G2B/); assert.match(journal, /FSSDiscoveryScan/); assert.match(journal, /SAAScanComplete/)
  const nav = JSON.parse(await fs.readFile(path.join(directory, 'NavRoute.json'), 'utf8')); assert.equal(nav.Route[1].StarSystem, 'Fixture Beta')
  assert.equal(journal, await fs.readFile(path.join(sourceDir, 'replay.jsonl'), 'utf8'))
  assert.notEqual(directory, await createNavigationFixture({ sourceDir, outputParent: root }))
})
